"""Write the restricted security rules (firebase/restricted/) from the normal ones.

The restricted rules are the normal rules with one change: "signed in" also requires the
custom claim that the backend gives only to the allowed accounts (AQUATRACK_ALLOWED_UIDS).
Everything else (ownership, validation, backend-only writes) is the same text, so the two
sets cannot drift apart: tests/test_demo_access.py fails when the generated files are stale.

    uv run python scripts/build_restricted_rules.py          # write
    uv run python scripts/build_restricted_rules.py --check  # exit 1 if stale

Deploy firebase/restricted/*.rules to the demonstration project only. The normal rules stay
the ones the emulators and every other environment use.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLAIM = "aquatrack_demo"  # must equal aquatrack.api.config.ACCESS_CLAIM
SIGNED_IN = "request.auth != null"
ALLOWED = f"request.auth != null && request.auth.token.{CLAIM} == true"
HEADER = (
    "// GENERATED by scripts/build_restricted_rules.py from firebase/{name}. Do not edit.\n"
    "// Restricted deployment: every rule also requires the custom claim `" + CLAIM + "`,\n"
    "// which the backend sets only on the accounts listed in AQUATRACK_ALLOWED_UIDS.\n"
)


def restricted(name: str, text: str, expected: int) -> str:
    found = text.count(SIGNED_IN)
    if found != expected:
        raise SystemExit(
            f"firebase/{name}: expected {expected} sign-in checks, found {found}. Review the "
            "rules and update scripts/build_restricted_rules.py: every rule must go through one."
        )
    return HEADER.format(name=name) + text.replace(SIGNED_IN, ALLOWED)


def build() -> dict[Path, str]:
    # Firestore: every rule calls signedIn(), the only place the check appears.
    # Storage: each of the three rules states it directly.
    return {
        ROOT / "firebase/restricted" / name: restricted(
            name, (ROOT / "firebase" / name).read_text(), expected
        )
        for name, expected in (("firestore.rules", 1), ("storage.rules", 3))
    }


def main() -> int:
    stale = False
    for path, text in build().items():
        if "--check" in sys.argv:
            if not path.is_file() or path.read_text() != text:
                print(f"stale: {path.relative_to(ROOT)}")
                stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
